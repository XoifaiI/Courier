pub fn is_reserved_field(name: &str) -> bool {
    let bytes = name.as_bytes();
    let temporary = bytes.len() > 1 && bytes[0].is_ascii_uppercase() && bytes[1..].iter().all(u8::is_ascii_digit);
    let screaming = bytes.iter().all(|byte| byte.is_ascii_uppercase() || byte.is_ascii_digit() || *byte == b'_');
    temporary || RESERVED_FIELDS.contains(&name) || (screaming && (name.contains('_') || name.len() > 2))
}
